    prop: { 'pile.logs': sheet(['p0', 'p2', 'p4'], 40, 24, COL.prop), fire: sheet(['cold', 'lit0', 'lit1'], 32, 24, COL.prop, { fps: 6 }), stake: sheet(['idle'], 12, 30, COL.prop),
      tent: sheet(['idle'], 60, 50, COL.prop), pack: sheet(['idle'], 20, 24, COL.prop) },
